-- Step 1: Ensure public.itineraries table exists with appropriate constraints
CREATE TABLE IF NOT EXISTS public.itineraries (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    destination TEXT NOT NULL,
    days INT NOT NULL CHECK (days >= 1 AND days <= 14),
    budget NUMERIC NOT NULL CHECK (budget > 0),
    travel_style TEXT NOT NULL,
    itinerary JSONB NOT NULL DEFAULT '{}'::jsonb
);

-- Step 2: Enable Row Level Security (RLS)
-- Safely protect table access without disabling RLS globally
ALTER TABLE public.itineraries ENABLE ROW LEVEL SECURITY;

-- Step 3: Grant standard table permissions to PostgREST roles
-- This resolves: "permission denied for table itineraries"
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.itineraries TO service_role;
GRANT SELECT, INSERT ON TABLE public.itineraries TO anon, authenticated;

-- Step 4: Configure Least-Privilege RLS Policies

-- Policy 1: Allow public & authenticated users to save their generated itineraries
-- This resolves: "new row violates row-level security policy for table 'itineraries'"
DROP POLICY IF EXISTS "Allow public insert to itineraries" ON public.itineraries;
CREATE POLICY "Allow public insert to itineraries"
ON public.itineraries
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- Policy 2: Allow reading saved itineraries
DROP POLICY IF EXISTS "Allow public select from itineraries" ON public.itineraries;
CREATE POLICY "Allow public select from itineraries"
ON public.itineraries
FOR SELECT
TO anon, authenticated
USING (true);

-- Step 5: Verify table schema and policies
COMMENT ON TABLE public.itineraries IS 'Stores personalized travel itineraries generated by the AI planner.';
